/// The single static map for Adventure mode -- ported from the Python
/// prototype's `map_data.py` (same ASCII-grid idea as `Level`, but only
/// '0' counts as a wall here; '1' and 'c' were that prototype's separate
/// floor-texture tiles (path/curve), which this first draft doesn't
/// distinguish -- both render as plain walkable floor, same as '-'.
enum AdventureMap {
    static var columns: Int { map.first?.count ?? 0 }
    static var rows: Int { map.count }

    static let walls: Set<GridPoint> = {
        var result: Set<GridPoint> = []
        for (rowFromTop, row) in map.enumerated() {
            let y = map.count - 1 - rowFromTop
            for (x, character) in row.enumerated() where character == "0" {
                result.insert(GridPoint(x: x, y: y))
            }
        }
        return result
    }()

    private static let map: [String] = [
        "000000000000-11-000000000000000000000000000000000000000000000000000000",
        "0------------11------------------------------------------------------0",
        "0------------11------------------------------------------------------0",
        "0------------11------------------------------------------------------0",
        "0------------11------------------------------------------------------0",

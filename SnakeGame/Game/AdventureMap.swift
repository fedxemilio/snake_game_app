/// Adventure mode's maps, one per stage (see `AdventureStage`). They're ASCII grids
/// like `Level`'s, but only '0' counts as a wall and '~' as sky above the surface
/// (which blocks like a wall but isn't drawn as rock); anything else is open water.
/// Stage 1's came from the Python prototype's `map_data.py`, whose '1' and 'c'
/// were floor-texture tiles (path/curve) with no gameplay meaning here.
///
/// Every map is the same size, `columns` x `rows`: the scene's geometry (cell
/// size, world size, camera bounds) is set once per run, so stages swap what's
/// in the world, never its size.
enum AdventureMap {
    static let columns = 70
    static let rows = 40

    /// The wall cells of `map`, flipping its row order so its first string is the
    /// top row (the highest `y`), per the grid's bottom-left origin.
    static func walls(in map: [String]) -> Set<GridPoint> {
        cells(in: map, marked: "0")
    }

    /// The sky cells of `map` ('~'), the same way round as `walls(in:)`.
    static func sky(in map: [String]) -> Set<GridPoint> {
        cells(in: map, marked: "~")
    }

    private static func cells(in map: [String], marked mark: Character) -> Set<GridPoint> {
        var result: Set<GridPoint> = []
        for (rowFromTop, row) in map.enumerated() {
            let y = map.count - 1 - rowFromTop
            for (x, character) in row.enumerated() where character == mark {
                result.insert(GridPoint(x: x, y: y))
            }
        }
        return result
    }

